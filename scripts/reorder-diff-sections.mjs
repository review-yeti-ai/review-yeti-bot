#!/usr/bin/env node
// Deterministic file-priority reordering for a unified diff.
//
// review-pipeline.js's planDiffBudget() already keeps the char-budget
// truncation honest: files are reviewed in the order they appear in the
// diff, and once the budget runs out later files are truncated or listed as
// omitted rather than silently dropped (files-omitted output, "not
// reviewed" PR-comment note). That machinery does not know or care *which*
// files come first -- it trusts diff order.
//
// For a diff assembled by the local-clone fallback (scripts/fetch-pr-diff.sh)
// there is no GitHub-imposed order to trust: a forward-merge or a huge
// backport can legitimately contain thousands of files, most of which are
// generated, vendored, or lockfile noise nobody needs a model to read. This
// module reorders diff sections so the budget spends itself on real source
// first: non-test source, then test source, then generated/lock/vendor/
// snapshot files last -- so if the budget runs out, it runs out on the
// lowest-value files, and the existing omitted-files disclosure still
// applies to them.
//
// This never drops content. It only changes section order; every "diff
// --git" section from the input appears exactly once in the output.

import { realpathSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

// Same shape as ct-review-actions policy/review-yeti.json's `exclude` field
// (docs/api/autogenerated/**, priv/repo/structure.sql, apm.lock.yaml,
// .apm/**), extended with the common generated/lock/vendor/snapshot
// families. Kept here rather than threaded through action.yml's deprecated
// `exclude` input because this only affects section order for the fallback
// path, not which files a persona is allowed to see.
export const DEFAULT_IGNORE_GLOBS = [
  '**/package-lock.json',
  '**/yarn.lock',
  '**/pnpm-lock.yaml',
  '**/*.lock',
  'apm.lock.yaml',
  '.apm/**',
  '**/vendor/**',
  '**/node_modules/**',
  '**/dist/**',
  '**/build/**',
  '**/__snapshots__/**',
  '**/*.snap',
  '**/*.min.js',
  '**/*.min.css',
  'docs/api/autogenerated/**',
  'priv/repo/structure.sql',
];

const TEST_PATH_PATTERN = /(^|\/)(tests?|__tests__|spec)(\/|$)|[._-](test|spec)\.[^/]+$/iu;

function globToRegExp(glob) {
  let out = '';
  for (let i = 0; i < glob.length; i += 1) {
    const ch = glob[i];
    if (ch === '*' && glob[i + 1] === '*') {
      out += '.*';
      i += 1;
      // Swallow an immediately following slash so `**/foo` matches `foo` at
      // the root, not just nested occurrences.
      if (glob[i + 1] === '/') i += 1;
    } else if (ch === '*') {
      out += '[^/]*';
    } else if (ch === '?') {
      out += '[^/]';
    } else if ('.+^${}()|[]\\'.includes(ch)) {
      out += `\\${ch}`;
    } else {
      out += ch;
    }
  }
  return new RegExp(`^${out}$`, 'u');
}

export function isIgnoredPath(filePath, ignoreGlobs = DEFAULT_IGNORE_GLOBS) {
  const normalized = String(filePath || '').replace(/^\.\//u, '');
  return ignoreGlobs.some((glob) => globToRegExp(glob).test(normalized));
}

export function isTestPath(filePath) {
  return TEST_PATH_PATTERN.test(String(filePath || ''));
}

// A "diff --git a/<path> b/<path>" header starts every section. Splitting on
// a lookahead keeps each header attached to its own section body.
const SECTION_HEADER_PATTERN = /^diff --git a\/(.+?) b\/(.+)$/mu;

function splitSections(diffText) {
  if (!diffText || !diffText.includes('diff --git')) {
    return { preamble: diffText || '', sections: [] };
  }
  const parts = diffText.split(/(?=^diff --git )/mu);
  const preamble = parts[0].startsWith('diff --git') ? '' : parts[0];
  const sectionTexts = preamble ? parts.slice(1) : parts;
  const sections = sectionTexts.map((text) => {
    const match = SECTION_HEADER_PATTERN.exec(text);
    // Prefer the b/ path (post-change path); falls back to a/ for deletions
    // where b/ is /dev/null.
    const path = match ? (match[2] === '/dev/null' ? match[1] : match[2]) : '';
    return { path, text };
  });
  return { preamble, sections };
}

function priorityOf(path, ignoreGlobs) {
  if (isIgnoredPath(path, ignoreGlobs)) return 2;
  if (isTestPath(path)) return 1;
  return 0;
}

/**
 * Reorder the "diff --git" sections of a unified diff so non-test source
 * comes first, test source second, and generated/lock/vendor/snapshot files
 * last. Stable within each priority tier -- original relative order is
 * preserved. Any leading preamble text (rare for `git diff` output, but
 * defensive) is kept in front.
 *
 * @param {string} diffText
 * @param {{ignoreGlobs?: string[]}} [options]
 * @returns {{text: string, order: string[], ignoredCount: number, testCount: number}}
 */
export function reorderDiffSections(diffText, options = {}) {
  const ignoreGlobs = options.ignoreGlobs || DEFAULT_IGNORE_GLOBS;
  const { preamble, sections } = splitSections(diffText);

  if (sections.length === 0) {
    return { text: diffText || '', order: [], ignoredCount: 0, testCount: 0 };
  }

  const indexed = sections.map((section, index) => ({
    ...section,
    index,
    priority: priorityOf(section.path, ignoreGlobs),
  }));

  indexed.sort((a, b) => (a.priority - b.priority) || (a.index - b.index));

  return {
    text: preamble + indexed.map((section) => section.text).join(''),
    order: indexed.map((section) => section.path),
    ignoredCount: indexed.filter((section) => section.priority === 2).length,
    testCount: indexed.filter((section) => section.priority === 1).length,
  };
}

async function main() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const diffText = Buffer.concat(chunks).toString('utf8');
  const result = reorderDiffSections(diffText);
  process.stdout.write(result.text);
  process.stderr.write(
    `reorder-diff-sections: ${result.order.length} files (${result.testCount} test, ${result.ignoredCount} ignored) moved to the tail\n`,
  );
}

const invokedPath = process.argv[1] ? pathToFileURL(realpathSync(process.argv[1])).href : '';
if (invokedPath === import.meta.url) {
  main().catch((error) => {
    process.stderr.write(`::error::${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}

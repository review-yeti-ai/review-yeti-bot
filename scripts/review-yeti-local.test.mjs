test('delegates to an installed CLI with a temporary 0600 config and cleans it up', () => {
  const tempRoot = mkdtempSync(path.join(os.tmpdir(), 'ct-review-yeti-local-test-'));
  const fakeCli = path.join(tempRoot, 'fake-reviewyeti');
  const receipt = path.join(tempRoot, 'delegation.json');
  const mcpConfigPath = path.join(tempRoot, 'mcp.json');
  writeFileSync(mcpConfigPath, JSON.stringify({
    servers: [{
      id: 'context7-local',
      name: 'Context7 local proxy',
      transport: 'http',
      url: 'http://127.0.0.1:4318/mcp',
      env: { CONTEXT7_API_KEY: 'secret-not-for-logs' },
    }],
  }));
  writeFileSync(fakeCli, `#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const configPath = path.join(process.env.REVIEW_YETI_CONFIG_DIR, '.review-yeti.yaml');
const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
const mcp = JSON.parse(process.env.MCP_CONFIG_JSON);
fs.writeFileSync(process.env.CT_REVIEW_YETI_TEST_RECEIPT, JSON.stringify({
  args: process.argv.slice(2),
  configMode: fs.statSync(configPath).mode & 0o777,
  transportNames: config.github_action.transports.map((transport) => transport.name),
  mcpServerIds: mcp.servers.map((server) => server.id),
  mcpSecretPresent: mcp.servers[0].env.CONTEXT7_API_KEY === 'secret-not-for-logs',
  publicationFlag: process.env.GITHUB_ACTIONS,
}));
process.stdout.write(JSON.stringify({ delegated: true }) + '\\n');
`, { mode: 0o700 });

  try {
    const output = execFileSync(
      path.join(repoRoot, 'scripts/review-yeti-local'),
      ['review', '--base', 'a'.repeat(40), '--head', 'b'.repeat(40), '--json', '--cli-bin', fakeCli, '--mcp-config', mcpConfigPath],
      {
        cwd: repoRoot,
        env: { ...process.env, CT_REVIEW_YETI_TEST_RECEIPT: receipt },
        encoding: 'utf8',
      },
    );
    const delegated = JSON.parse(readFileSync(receipt, 'utf8'));
    assert.equal(JSON.parse(output).delegated, true);
    assert.deepEqual(delegated.args, ['review', '--base', 'a'.repeat(40), '--head', 'b'.repeat(40), '--json']);
    assert.equal(delegated.configMode, 0o600);
    assert.deepEqual(delegated.transportNames, ['bifrost', 'openrouter-primary']);
    assert.deepEqual(delegated.mcpServerIds, ['context7-local']);
    assert.equal(delegated.mcpSecretPresent, true);
    assert.equal(delegated.publicationFlag, 'false');

    const configDir = process.env.REVIEW_YETI_CONFIG_DIR;
    assert.equal(configDir, undefined, 'launcher must not leak its temporary config into the parent process');
  } finally {
    rmSync(tempRoot, { recursive: true, force: true });
  }
});
